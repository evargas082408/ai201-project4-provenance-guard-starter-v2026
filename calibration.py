#!/usr/bin/env python3
"""
Calibration inputs for Milestones 3 and 4, and a table of what each signal says.

    python calibration.py            # both signals, combined score, label
    python calibration.py --model    # signal one only (Milestone 3)

Where the texts come from, so nobody mistakes them for something they're not:

  - "AI" texts were generated by Claude (an AI model) from plain prompts like
    "write a paragraph about time management for students", unedited.
  - "lightly-edited AI" is one of those, hand-edited: contractions, a dash,
    a fragment, a casual word or two.
  - The human texts are published, public-domain prose (all pre-1929), chosen
    because nobody can argue a model wrote them. They are NOT my own writing:
    criterion 1 needs my own writing, which goes in scenarios.py in unit 8.
"""

